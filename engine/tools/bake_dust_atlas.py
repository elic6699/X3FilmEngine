"""Bake approved grayscale masks into the engine; Pillow is needed only to rebake."""
from pathlib import Path
import json
from PIL import Image

root = Path(__file__).resolve().parents[2]
base = root / 'engine/third_party/film_damage_simulator'
assets = json.loads((base / 'dust_assets.json').read_text())['assets']
assert [sum(a['category'] == c for a in assets) for c in ('Dust', 'Short hair', 'Long hair')] == [64, 32, 16]
tiles = []
for a in assets:
    image = Image.open(base / 'dust_masks' / a['file'])
    assert image.mode == 'L' and image.getextrema()[1] > 0
    radius = max(a['annotation_span']) / 2
    cx, cy = [a['center'][i] - a['bbox'][i] for i in (0, 1)]
    # q spans +/-1.5; fit uniformly to preserve the source geometry and padding.
    tile = image.transform((128, 128), Image.Transform.AFFINE,
                           (3 * radius / 128, 0, cx - 1.5 * radius,
                            0, 3 * radius / 128, cy - 1.5 * radius), Image.Resampling.BILINEAR)
    tiles.append(tile.resize((64, 64), Image.Resampling.LANCZOS).tobytes())
assert len(set(tiles)) == 112 and all(any(t) for t in tiles)
data = b''.join(tiles)
lines = ['// Generated by tools/bake_dust_atlas.py; Daniela Ivanova, CC BY 4.0.',
         '// 64 dust + 32 short fibers + 16 long fibers, 64x64 grayscale tiles.',
         '// See third_party/film_damage_simulator/dust_assets.json and SOURCE.md.',
         'static constexpr unsigned char kDustAtlas[] = {']
lines += [','.join(str(b) for b in data[i:i+64]) + ',' for i in range(0, len(data), 64)]
lines += ['};', 'static_assert(sizeof(kDustAtlas) == 112 * 64 * 64);']
(root / 'engine/src/pipeline/dust_atlas.h').write_text('\n'.join(lines) + '\n')
print(f'Baked {len(tiles)} unique grayscale tiles ({len(data)} bytes)')
