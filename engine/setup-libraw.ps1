# Download the pinned fork commit, verify before extraction. No Python needed.
#
# Keep these values identical to setup-libraw.sh: the POSIX twin pins the same
# commit, archive SHA-256 and short directory name.
[CmdletBinding()]
param([string]$DependencyDirectory = (Join-Path $PSScriptRoot '..\..\deps'))
$ErrorActionPreference = 'Stop'
$DependencyDirectory = [IO.Path]::GetFullPath($DependencyDirectory)
New-Item -ItemType Directory -Path $DependencyDirectory -Force | Out-Null
# The fork carries upstream LibRaw 0.22.x plus the project's own patches. The
# commit is pinned, not the branch: master moves and would silently change RAW
# decode between builds.
$commit = 'e419de08001de28ae6988ecb22df47e52b9c5eaa'
$archive = Join-Path $DependencyDirectory "LibRaw-$commit.zip"
$source = Join-Path $DependencyDirectory 'LibRaw-e419de0'
$url = "https://codeload.github.com/elic6699/LibRaw/zip/$commit"
$expected = 'edd6198eb16e347645e8d967c9d6f83226ae8b65ca6e9862196f61db9d9c8506'
if (-not (Test-Path -LiteralPath $archive)) {
    Invoke-WebRequest -Uri $url -OutFile "$archive.partial"
    Move-Item -LiteralPath "$archive.partial" -Destination $archive -Force
}
if ((Get-FileHash -LiteralPath $archive -Algorithm SHA256).Hash.ToLowerInvariant() -ne $expected) {
    throw 'LibRaw archive checksum mismatch; existing files were not extracted or changed.'
}
Add-Type -AssemblyName System.IO.Compression.FileSystem
$zip = [IO.Compression.ZipFile]::OpenRead($archive)
try {
    $top = $zip.Entries[0].FullName.Split('/')[0]
    if (-not $top) { throw 'LibRaw archive has no top-level directory' }
    function Test-LibRawTree([string]$Root) {
        $Root = [IO.Path]::GetFullPath($Root)
        $seen = [Collections.Generic.HashSet[string]]::new([StringComparer]::OrdinalIgnoreCase)
        foreach ($entry in $zip.Entries) {
            if (-not $entry.Name) { continue }
            $relative = $entry.FullName.Substring($top.Length + 1)
            $target = [IO.Path]::GetFullPath((Join-Path $Root $relative))
            if (-not $target.StartsWith($Root + [IO.Path]::DirectorySeparatorChar, [StringComparison]::OrdinalIgnoreCase)) {
                throw "Unsafe LibRaw archive path: $($entry.FullName)"
            }
            [void]$seen.Add($target)
            if (-not (Test-Path -LiteralPath $target -PathType Leaf)) { throw "Incomplete LibRaw source tree: $target" }
            $stream = $entry.Open()
            $hasher = [Security.Cryptography.SHA256]::Create()
            try { $digest = [BitConverter]::ToString($hasher.ComputeHash($stream)).Replace('-', '').ToLowerInvariant() }
            finally { $hasher.Dispose(); $stream.Dispose() }
            if ((Get-FileHash -LiteralPath $target -Algorithm SHA256).Hash.ToLowerInvariant() -ne $digest) {
                throw "Modified LibRaw source file: $target. Existing files were not overwritten."
            }
        }
        foreach ($file in Get-ChildItem -LiteralPath $Root -File -Recurse) {
            if ($seen.Contains($file.FullName)) { continue }
            # LibRaw's own Makefile.devel compiles in-tree (object/, lib/, bin/).
            # Those outputs are regenerated by the build and would otherwise make
            # every re-run look like tampering; every archive file is still
            # compared byte for byte above.
            # Path.GetRelativePath is .NET Core only; the build hosts also run
            # Windows PowerShell 5.1, so derive the first segment by hand.
            $rel = $file.FullName.Substring($Root.Length).TrimStart([IO.Path]::DirectorySeparatorChar)
            $first = $rel.Split([IO.Path]::DirectorySeparatorChar)[0]
            if ($first -in @('object', 'lib', 'bin')) { continue }
            if ($file.Extension -in @('.o', '.obj', '.a', '.lib', '.so', '.dylib', '.pdb', '.ilk')) { continue }
            throw "Unexpected file in pinned LibRaw source: $($file.FullName)"
        }
    }
    if (Test-Path -LiteralPath $source) {
        Test-LibRawTree $source
    } else {
        $staged = "$source.partial"
        if (Test-Path -LiteralPath $staged) { Remove-Item -LiteralPath $staged -Recurse -Force }
        [IO.Compression.ZipFile]::ExtractToDirectory($archive, $staged)
        $inner = Join-Path $staged $top
        Test-LibRawTree $inner
        Move-Item -LiteralPath $inner -Destination $source
        Remove-Item -LiteralPath $staged -Recurse -Force
    }
} finally { $zip.Dispose() }
# Same record build-host.sh, cmake/LibRaw.cmake and stage-host.sh read.
Set-Content -LiteralPath (Join-Path $DependencyDirectory 'libraw-source.path') -Value $source -NoNewline -Encoding ascii
Write-Output "LibRaw $commit : $source (archive SHA256 and existing source verified)."
